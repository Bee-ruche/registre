#!/usr/bin/env python3
"""English names, step 1d (ruche-0153; docs/english-migration.md, sections 12 and 13): the switch script. From a commit of main
(the base), it writes the switch's generated commit in a new worktree, dormant until ruche-0145 runs it during the freeze:
    python3 -I outils/migration/switch.py --base REV --out DIR [--repo DIR]
Every path moves by git mv (history follows); each data file and schema is translated by its family (rename.py), each code
file by the code renamers (rename_code.py), each other file as the map's hand entry says: byte-identical, replaced, its
`bee <command>` and options renamed inside code spans and blocks (change 10), or removed. Nothing else is written, and the same
base always gives the same tree (its SHA is printed). It runs only as the base's own code (this script, the renamers, the
map, bee.py): the proofs (bee check-migration) then read the same map from the same base. Exit 0: the generated commit, as the
last line says; 1: refused, nothing committed.
"""
import sys

if __name__ == "__main__" and not sys.flags.isolated:
    sys.exit("switch.py: run it isolated, python3 -I outils/migration/switch.py …, so that nothing shadows a module")

import argparse, os, pathlib, subprocess  # noqa: E401, E402

SELF = pathlib.Path(__file__).resolve()
sys.path += [str(SELF.parent.parent), str(SELF.parent)]  # last: never in front of the standard library or PyYAML
import bee, rename, rename_code  # noqa: E402, E401

MESSAGE = "English names: the switch, generated by outils/migration/switch.py from {base} (ruche-0145)\n"


def translated(files, names, cm):
    """{English path: bytes} of the switch of files ({path: bytes}, the base's), as P2 and P1 prove it: the first rule that matches
    decides, in rename.check's order (a family, a schema, the code, then the first hand entry)."""
    out = {}
    for p, content in sorted(files.items()):
        fams, schema, code = names.families_of(p), names.schemas.get(p), p in names.code
        if fams or schema:
            text = content.decode("utf-8")
            out[names.path(p)] = (names.schema(schema, text, False) if schema else names.translate(fams[0], text)).encode("utf-8")
        elif code:
            text = content.decode("utf-8")
            out[names.path(p)] = (cm.rename_python(text, p) if p.endswith(".py") else cm.rename_shell(text, p))[0].encode("utf-8")
        elif not (h := next((h for r, h in names.hand if r.match(p)), {})).get("removed"):
            out[names.path(p)] = names.hand_bytes(h, p, files)
    return out


def scanned(names, new):
    """The files of the new tree change 10's scan reads: the workflows and shell scripts the switch renames, and every file whose
    commands it renames in its code (docs/**, the tree's nodes, .claude/**, AGENTS.md); never a file kept as written on purpose."""
    out = []
    for q in sorted(new):
        p, fams = names.path(q, True), names.families_of(names.path(q, True))
        hand = {} if fams or p in names.code else next((h for r, h in names.hand if r.match(p)), {})
        if p in names.code and not p.endswith(".py") or hand.get("commands") or fams and names.fam[fams[0]].get("commands"):
            out.append(q)
    return out


def old_names(names, cm, new):
    """Change 10's scan (plan, section 12): {path: [(line, text)]}, each old command name left after bee in the code of a scanned file."""
    return {q: found for q in scanned(names, new) if (found := cm.old_commands(new[q].decode("utf-8"), q))}


def own(files):
    """The base's map and its CodeMap, if this script, the renamers and bee.py are the base's own; else rename.Problem."""
    if (at := next((c for c in rename.MAPS if c in files), None)) is None:
        raise rename.Problem(f"no {rename.MAP} at the base")
    tools = at.rpartition("/migration/")[0]
    for path, live in ((f"{tools}/migration/switch.py", SELF), (f"{tools}/migration/rename.py", rename.SELF),
                       (f"{tools}/migration/rename_code.py", rename_code.SELF), (f"{tools}/bee.py", pathlib.Path(bee.__file__).resolve())):
        if files.get(path) != live.read_bytes():
            raise rename.Problem(f"{live} is not the base's {path}: run the base's own switch script, python3 -I, from its checkout")
    names = rename.Names(files[at].decode("utf-8"))
    cm = rename_code.CodeMap(names, files[rename_code.IDS[rename.MAPS.index(at)]].decode("utf-8"))
    names.cli = cm.commands  # change 10: the base's command table, as P2 reads it
    return names, cm


def git(repo, *argv, **k):
    return subprocess.run(["git", "-C", str(repo), *argv], capture_output=True, check=True, **k).stdout.decode("utf-8").strip()


def write(repo, base, out):
    """The generated commit of the switch of base, in a new worktree out (detached at base): git mv for every path the map moves,
    the translated bytes, git rm for removed files. Returns (its SHA, its tree's SHA)."""
    modes, files = {}, None
    files = rename.tree_files(repo, base, modes)
    names, cm = own(files)
    new = translated(files, names, cm)
    if left := old_names(names, cm, new):  # change 10: fail closed
        raise rename.Problem("old command names left (change 10): " + "; ".join(f"{q}:{n}: {x}" for q, f in left.items() for n, x in f[:3]))
    if pathlib.Path(out).exists():
        raise rename.Problem(f"{out} exists: the switch is written in a new worktree")
    git(repo, "worktree", "add", "-q", "--detach", str(out), base)
    out = pathlib.Path(out)
    for p in sorted(files):
        q = names.path(p)
        if q not in new:
            git(out, "rm", "-q", "--", p)
        elif q != p:
            (out / q).parent.mkdir(parents=True, exist_ok=True)
            git(out, "mv", "--", p, q)
    for q, content in sorted(new.items()):
        if (out / q).read_bytes() != content:
            (out / q).write_bytes(content)
    git(out, "add", "-A", ".")
    tree = git(out, "write-tree")
    got = rename.tree_files(out, tree, (got_modes := {}))
    if got != new or any(got_modes[q] != modes[p] for p in files if (q := names.path(p)) in new):
        raise rename.Problem("the worktree does not hold exactly the translation (a file left over, or a mode changed)")
    env = {**os.environ, **{f"GIT_{r}_DATE": git(repo, "show", "-s", "--format=%cI", base) for r in ("AUTHOR", "COMMITTER")}}
    git(out, "commit", "-q", "--no-verify", "-m", MESSAGE.format(base=git(repo, "rev-parse", base)), env=env)
    return git(out, "rev-parse", "HEAD"), tree


def main(argv=None):
    p = argparse.ArgumentParser(prog="switch.py", description=__doc__.split("\n\n")[0])
    p.add_argument("--base", required=True, help="the commit of main the switch translates")
    p.add_argument("--out", required=True, help="a new worktree, where the generated commit is written (detached)")
    p.add_argument("--repo", default=str(SELF.parents[2]))
    a = p.parse_args(argv)
    try:
        sha, tree = write(a.repo, a.base, a.out)
    except (rename.Problem, bee.ErreurBee, subprocess.CalledProcessError, OSError, UnicodeDecodeError, KeyError, TypeError) as e:
        print(f"✗ {type(e).__name__}: {e}" + (f": {e.stderr.decode('utf-8', 'replace').strip()}" if isinstance(e, subprocess.CalledProcessError) and e.stderr else ""))
        return 1
    print(f"✓ the generated commit {sha} (tree {tree}) is the switch of the base {git(a.repo, 'rev-parse', a.base)}, in {a.out}; "
          "no old command name is left in its workflows, scripts, docs, nodes or skill (change 10).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
